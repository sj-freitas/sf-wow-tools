// Writes the database as GuildAssistantDatabase's Data.lua (the game's data, gamedata.mjs). Recipes
// and items are kept as text, one line each, fields separated by tabs, and only turned into tables
// when a profession is first looked at in game (Core.lua's Core.load): loading text is cheap,
// thousands of tables aren't. Core.lua reads this format: keep the two in step (the addon's specs
// load the fixture this writes, dev/GuildAssistantDatabase/Data.fixture.lua).
//
// Data.lua (format 2):
//   recipe: spell id, name, skill to learn, skill-up colours ("yellow,green,grey"), item made
//     ("id,min,max", empty for an enchant), reagents ("id:count;…"), how the game teaches it
//     (0 trainer or recipe item, 1 at a skill, 2 with the profession), that skill, recipe items ("id;…")
//   item: id, name (empty when the game's tables lack it), quality, required level, inventory type,
//     icon (file id), kind ("Chest (Plate)"), stats ("Strength, Stamina"), skill to use (recipe
//     items), class id, subclass id
// Where recipes come from isn't in the game's data: sources companion addons add it (the format is
// in Core.lua, "Sources companions").

/** Text that fits in a field: no tabs, line breaks or list separators. */
const field = (text) => String(text ?? '').replace(/[\t\r\n;]+/g, ' ').replace(/ {2,}/g, ' ').trim();

export function recipeLine(recipe) {
  return [
    recipe.id,
    field(recipe.name),
    recipe.skill,
    recipe.colors.join(','),
    recipe.creates ? `${recipe.creates.id},${recipe.creates.min},${recipe.creates.max}` : '',
    recipe.reagents.map((r) => `${r.id}:${r.count}`).join(';'),
    recipe.acquire || 0,
    recipe.acquireSkill || '',
    recipe.recipeItems.join(';'),
  ].join('\t');
}

export function itemLine(item) {
  return [
    item.id,
    field(item.name),
    item.quality,
    item.level || '',
    item.slot || '',
    item.icon || '',
    field(item.kind),
    field(item.stats),
    item.skill || '',
    item.classID || '',
    item.subclassID || '',
  ].join('\t');
}

/** A Lua long string holding `text`, with a level of "=" that doesn't occur in it. */
export function longString(text) {
  let level = '';
  while (text.includes(`]${level}]`)) level += '=';
  // A long string drops a line break right after its opening bracket: start with one.
  return `[${level}[\n${text}]${level}]`;
}

const quote = (text) => JSON.stringify(String(text ?? '')); // a JSON string is a valid Lua one here

/** GuildAssistantDatabase's Data.lua for `database` (gamedata.mjs's buildDatabase). */
export function toLua(database) {
  const lines = [
    `-- GuildAssistant Database: recipe data from the game's own tables (${database.version} ${database.build}), fetched ${database.fetched}.`,
    '-- Generated by `npm run database` in addons/ (scripts/database): don\'t edit it by hand.',
    '',
    'local _, ns = ...',
    'ns.Data = {',
    '    format = 2,',
    `    version = ${quote(database.version)},`,
    `    build = ${quote(database.build)},`,
    `    fetched = ${quote(database.fetched)},`,
    '    professions = {',
  ];
  for (const profession of database.professions) {
    lines.push(
      '        {',
      `            name = ${quote(profession.name)}, skill = ${profession.skill}, count = ${profession.recipes.length},`,
      `            recipes = ${longString(profession.recipes.map(recipeLine).join('\n'))},`,
      `            items = ${longString(profession.items.map(itemLine).join('\n'))},`,
      '        },',
    );
  }
  lines.push('    },', '}', '');
  return lines.join('\n');
}
