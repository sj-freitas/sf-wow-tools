// What players found of how recipes are obtained, for GuildAssistant Database's Found.lua: their
// GuildAssistant Professions addons record it in game (vendors, trainers, loot, quest rewards), it
// reaches Guild Assistant with their professions file, and Guild Assistant publishes everything
// gathered (GET /api/recipe-sources). The data build (build.mjs) puts it in the addon as a source
// that only adds (not complete: it hides nothing), reviewed in the pull request before it ships.
import { longString } from './lua.mjs';

/** Guild Assistant, where the findings are gathered (GUILD_ASSISTANT_URL to use another). */
export const GUILD_ASSISTANT = process.env.GUILD_ASSISTANT_URL ?? 'https://guildassistant.app';

/** Everything gathered: { items: [{ id, entries: [{ entry }] }], trainers: [{ recipe, cost, entries }] }. */
export async function fetchFound(base = GUILD_ASSISTANT, fetcher = fetch) {
  const response = await fetcher(`${base}/api/recipe-sources`, { headers: { Accept: 'application/json' } });
  if (!response.ok) throw new Error(`${base}/api/recipe-sources: HTTP ${response.status}`);
  return response.json();
}

// What a field may hold, as the addon writes it (Guild Assistant checks it on import too).
const ITEM_ENTRY = /^[VDOFQ](\d{1,6}|:[^=;\t\n]{1,60})?=[^;\t\n]{0,60}$/;
const TRAINER_ENTRY = /^[^=;\t\n]{0,60}=[^=;\t\n]{1,60}$/;
const TRAINER_RECIPE = /^(item:\d{1,8}|name:[^=;\t\n]{1,80})$/;

const entriesOf = (list, pattern) =>
  [...new Set((Array.isArray(list) ? list : []).map((e) => e?.entry).filter((e) => typeof e === 'string' && pattern.test(e)))].sort();

/** Found.lua's text for what was gathered (`published`, as fetched), or null when there's nothing. */
export function toFoundLua(published, fetched) {
  const items = (published?.items ?? [])
    .filter((item) => Number.isInteger(item?.id) && item.id > 0)
    .map((item) => [item.id, entriesOf(item.entries, ITEM_ENTRY)])
    .filter(([, entries]) => entries.length > 0)
    .sort((a, b) => a[0] - b[0])
    .map(([id, entries]) => [id, '', '', '', entries.join(';')].join('\t'));
  const recipes = (published?.trainers ?? [])
    .filter((trainer) => typeof trainer?.recipe === 'string' && TRAINER_RECIPE.test(trainer.recipe))
    .map((trainer) => [trainer.recipe, Number.isInteger(trainer.cost) && trainer.cost > 0 ? trainer.cost : '', entriesOf(trainer.entries, TRAINER_ENTRY)])
    .filter(([, , entries]) => entries.length > 0)
    .sort((a, b) => a[0].localeCompare(b[0]))
    .map(([recipe, cost, entries]) => [recipe, '6', cost, entries.join(';')].join('\t'));
  if (items.length === 0 && recipes.length === 0) return null;
  return [
    `-- GuildAssistant Database: how recipes are obtained, as players' GuildAssistant Professions found it in game, fetched ${fetched}.`,
    '-- Gathered by Guild Assistant from their professions files; generated by `npm run database` in addons/',
    "-- (scripts/database/found.mjs): don't edit it by hand. A source that only adds (Core.lua, \"Sources companions\").",
    '',
    'GuildAssistantDatabaseSources = GuildAssistantDatabaseSources or {}',
    'table.insert(GuildAssistantDatabaseSources, {',
    '    name = "found by players",',
    `    recipes = ${longString(recipes.join('\n'))},`,
    `    items = ${longString(items.join('\n'))},`,
    '})',
    '',
  ].join('\n');
}

/** Found.lua when nothing has been found yet: it adds no source. */
export const EMPTY_FOUND = [
  '-- GuildAssistant Database: how recipes are obtained, as players\' GuildAssistant Professions found it in game.',
  '-- Nothing yet: `npm run database` in addons/ (scripts/database/found.mjs) fills it in from Guild Assistant.',
  '',
].join('\n');
